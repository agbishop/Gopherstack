// UpdateMaintenanceWindow updates a maintenance window.
func (b *InMemoryBackend) UpdateMaintenanceWindow(
	ctx context.Context,
	input *UpdateMaintenanceWindowInput,
) (*UpdateMaintenanceWindowOutput, error) {
	region := getRegion(ctx)
	b.mu.Lock("UpdateMaintenanceWindow")
	defer b.mu.Unlock()

	windows := b.maintenanceWindowsStore(region)
	mwPtr, exists := windows.Get(input.WindowID)
	if !exists {
		return nil, ErrMaintenanceWindowNotFound
	}

	mw := *mwPtr

	if input.Name != "" {
		mw.Name = input.Name
	}

	if input.Description != "" {
		mw.Description = input.Description
	}

	if input.Schedule != "" {
		mw.Schedule = input.Schedule
	}

	if input.Duration != 0 {
		mw.Duration = input.Duration
	}

	if input.Cutoff != 0 {
		mw.Cutoff = input.Cutoff
	}

	if input.Enabled != nil {
		mw.Enabled = *input.Enabled
	}

	if input.AllowUnassociatedTargets != nil {
		mw.AllowUnassociatedTargets = *input.AllowUnassociatedTargets
	}

	if input.ScheduleOffset != nil {
		mw.ScheduleOffset = *input.ScheduleOffset
	}

	if input.ScheduleTimezone != "" {
		mw.ScheduleTimezone = input.ScheduleTimezone
	}

	if input.StartDate != "" {
		mw.StartDate = input.StartDate
	}

	if input.EndDate != "" {
		mw.EndDate = input.EndDate
	}

	mw.ModifiedDate = UnixTimeFloat(timeNow())
	windows.Put(&mw)

	out := mw
	out.NextExecutionTime = mwNextExecutionTime()

	return &UpdateMaintenanceWindowOutput{MaintenanceWindow: out}, nil
}

// DeleteMaintenanceWindow removes a maintenance window by ID.
func (b *InMemoryBackend) DeleteMaintenanceWindow(
	ctx context.Context,
	input *DeleteMaintenanceWindowInput,
) (*DeleteMaintenanceWindowOutput, error) {
	region := getRegion(ctx)
	b.mu.Lock("DeleteMaintenanceWindow")
	defer b.mu.Unlock()

	mwTable := b.maintenanceWindowsStore(region)
	mwTable.Delete(input.WindowID)

	targets := b.maintenanceWindowTargetsStore(region)
	for _, t := range targets.All() {
		if t.WindowID == input.WindowID {
			targets.Delete(t.WindowTargetID)
		}
	}

	tasks := b.maintenanceWindowTasksStore(region)
	for _, t := range tasks.All() {
		if t.WindowID == input.WindowID {
			tasks.Delete(t.WindowTaskID)
		}
	}

	delete(b.miscResourceTagsStore(region), input.WindowID)
	cleanupEmptyInnerMap(b.miscResourceTags, region)

	return &DeleteMaintenanceWindowOutput{WindowID: input.WindowID}, nil
}

