// CreateMaintenanceWindow creates a new maintenance window.
func (b *InMemoryBackend) CreateMaintenanceWindow(
	ctx context.Context,
	input *CreateMaintenanceWindowInput,
) (*CreateMaintenanceWindowOutput, error) {
	if input.Name == "" {
		return nil, fmt.Errorf("%w: Name is required", ErrValidationException)
	}

	if input.Schedule == "" {
		return nil, fmt.Errorf("%w: Schedule is required", ErrValidationException)
	}

	const (
		minWindowDuration = int32(1)
		maxWindowDuration = int32(24)
	)
	if input.Duration < minWindowDuration || input.Duration > maxWindowDuration {
		return nil, fmt.Errorf(
			"%w: Duration must be between 1 and 24 hours",
			ErrValidationException,
		)
	}
	if input.Cutoff >= input.Duration {
		return nil, fmt.Errorf("%w: Cutoff must be less than Duration", ErrValidationException)
	}

	region := getRegion(ctx)
	b.mu.Lock("CreateMaintenanceWindow")
	defer b.mu.Unlock()

	windowID := windowIDPrefix + uuid.NewString()
	now := UnixTimeFloat(time.Now())

	mw := MaintenanceWindow{
		WindowID:                 windowID,
		Name:                     input.Name,
		Description:              input.Description,
		Schedule:                 input.Schedule,
		ScheduleTimezone:         input.ScheduleTimezone,
		ScheduleOffset:           input.ScheduleOffset,
		StartDate:                input.StartDate,
		EndDate:                  input.EndDate,
		Duration:                 input.Duration,
		Cutoff:                   input.Cutoff,
		AllowUnassociatedTargets: input.AllowUnassociatedTargets,
		Enabled:                  true,
		CreatedDate:              now,
		ModifiedDate:             now,
	}

	b.maintenanceWindowsStore(region).Put(&mw)

	if len(input.Tags) > 0 {
		if b.miscResourceTags[region] == nil {
			b.miscResourceTags[region] = make(map[string]map[string]string)
		}
		miscTags := b.miscResourceTagsStore(region)
		if miscTags[windowID] == nil {
			miscTags[windowID] = make(map[string]string)
		}
		for _, t := range input.Tags {
			miscTags[windowID][t.Key] = t.Value
		}
	}

	return &CreateMaintenanceWindowOutput{WindowID: windowID}, nil
}

const mwExecIDPrefix = "mwexec-"

// mwExecID builds a deterministic execution ID from a window ID.
// mwToIdentity projects a stored MaintenanceWindow onto the narrower
// MaintenanceWindowIdentity listing shape (DescribeMaintenanceWindows,
// DescribeMaintenanceWindowsForTarget).
func mwToIdentity(mw *MaintenanceWindow) MaintenanceWindowIdentity {
	return MaintenanceWindowIdentity{
		WindowID:          mw.WindowID,
		Name:              mw.Name,
		Description:       mw.Description,
		Schedule:          mw.Schedule,
		ScheduleTimezone:  mw.ScheduleTimezone,
		StartDate:         mw.StartDate,
		EndDate:           mw.EndDate,
		NextExecutionTime: mwNextExecutionTime(),
		Duration:          mw.Duration,
		Cutoff:            mw.Cutoff,
		ScheduleOffset:    mw.ScheduleOffset,
		Enabled:           mw.Enabled,
	}
}

func mwExecID(windowID string) string { return mwExecIDPrefix + windowID }

// mwNextExecutionTime returns a synthetic next-run time -- this backend has
// no real cron/rate-expression evaluator to derive a genuine one from
// Schedule, matching the same fixed-offset heuristic
// DescribeMaintenanceWindowSchedule already uses.
func mwNextExecutionTime() string {
	return time.Now().UTC().Add(mwExecutionScheduleHours * time.Hour).Format(time.RFC3339)
}

// mwWindowIDFromExec extracts the window ID from a deterministic execution ID.
// Returns ("", false) if the execution ID was not generated by mwExecID.
func mwWindowIDFromExec(execID string) (string, bool) {
	if len(execID) <= len(mwExecIDPrefix) || execID[:len(mwExecIDPrefix)] != mwExecIDPrefix {
		return "", false
	}

	return execID[len(mwExecIDPrefix):], true
}

// DescribeMaintenanceWindowExecutions returns execution records for a window.
// When the window exists it returns a single synthetic execution record derived
// from the window's state (simulating that the window has run once).
func (b *InMemoryBackend) DescribeMaintenanceWindowExecutions(
	ctx context.Context,
	input *DescribeMaintenanceWindowExecutionsInput,
) (*DescribeMaintenanceWindowExecutionsOutputFull, error) {
	if input.WindowID == "" {
		return nil, fmt.Errorf("%w: WindowId is required", ErrValidationException)
	}

	region := getRegion(ctx)
	b.mu.RLock("DescribeMaintenanceWindowExecutions")
	defer b.mu.RUnlock()

	win, exists := b.maintenanceWindowsStore(region).Get(input.WindowID)
	if !exists {
		return &DescribeMaintenanceWindowExecutionsOutputFull{
			WindowExecutions: []MaintenanceWindowExecution{},
		}, nil
	}

	var execTime time.Time
	if win.CreatedDate > 0 {
		execTime = time.Unix(int64(win.CreatedDate), 0).UTC()
	} else {
		execTime = time.Now().UTC()
	}

	endTime := execTime.Add(time.Duration(win.Duration) * time.Hour)

	return &DescribeMaintenanceWindowExecutionsOutputFull{
		WindowExecutions: []MaintenanceWindowExecution{
			{
				WindowID:          win.WindowID,
				WindowExecutionID: mwExecID(win.WindowID),
				Status:            commandStatusSuccess,
				StartTime:         UnixTimeFloat(execTime),
				EndTime:           UnixTimeFloat(endTime),
			},
		},
	}, nil
}

// DescribeMaintenanceWindowExecutionTasks returns task executions for a window execution.
// Derives the window ID from the execution ID and looks up registered tasks for that window.
func (b *InMemoryBackend) DescribeMaintenanceWindowExecutionTasks(
	ctx context.Context,
	input *DescribeMaintenanceWindowExecutionTasksInput,
) (*DescribeMaintenanceWindowExecutionTasksOutputFull, error) {
	if input.WindowExecutionID == "" {
		return nil, fmt.Errorf("%w: WindowExecutionId is required", ErrValidationException)
	}

	region := getRegion(ctx)
	b.mu.RLock("DescribeMaintenanceWindowExecutionTasks")
	defer b.mu.RUnlock()

	windowID, ok := mwWindowIDFromExec(input.WindowExecutionID)
	if !ok {
		return &DescribeMaintenanceWindowExecutionTasksOutputFull{
			WindowExecutionTaskIdentities: []MaintenanceWindowExecutionTask{},
		}, nil
	}

	tasks := b.maintenanceWindowTasksStore(region)
	result := make([]MaintenanceWindowExecutionTask, 0)

	for _, task := range tasks.All() {
		if task.WindowID != windowID {
			continue
		}

		result = append(result, MaintenanceWindowExecutionTask{
			WindowExecutionID: input.WindowExecutionID,
			TaskExecutionID:   "taskexec-" + task.WindowTaskID,
			TaskARN:           task.TaskArn,
			Status:            commandStatusSuccess,
			StartTime:         UnixTimeFloat(time.Now()),
		})
	}

	sort.Slice(result, func(i, k int) bool {
		return result[i].TaskExecutionID < result[k].TaskExecutionID
	})

	if len(result) == 0 {
		result = []MaintenanceWindowExecutionTask{}
	}

	page, next := paginateSlice(result, input.NextToken, maxResultsOrZero(input.MaxResults), defaultDescribeMaxResults)

	return &DescribeMaintenanceWindowExecutionTasksOutputFull{
		WindowExecutionTaskIdentities: page,
		NextToken:                     next,
	}, nil
}

